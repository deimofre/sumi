  /** 筆が置いた顔料のうち、接地した繊維にその場で定着する割合。残りは水に乗ってにじむ。大きいほど線が濃くにじみが薄い */
  brushFixFraction: 0.5,
  /** なぞり 1 サンプル (短辺の 0.5%) あたりの水と顔料の供給量 */
